"""Descriptive analysis of the UrbanMask observation base.

Usage: python scripts/analysis.py
Writes results/summary.md, results/*.csv and results/figures/*.png.
"""
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
FIG = RES / "figures"
FIG.mkdir(parents=True, exist_ok=True)
FEAT = ["ndvi", "ndvi_re", "gndvi", "savi", "mndwi", "ndbi", "ui", "nbi", "bsi", "baei", "ibi",
        "ndvi_std", "entropy", "ndbi_std"]
plt.rcParams.update({"font.size": 8, "font.family": "DejaVu Sans"})

def md(t, index=True, nd=2):
    """Markdown table with thousands separators for integers."""
    t = t.copy()
    for c in t.columns:
        if c in ("year", "from", "to"):
            continue
        if pd.api.types.is_integer_dtype(t[c]):
            t[c] = t[c].map(lambda v: f"{v:,}")
        elif pd.api.types.is_float_dtype(t[c]):
            t[c] = t[c].map(lambda v: f"{v:.{nd}f}")
    return t.to_markdown(index=index)


df = pd.concat([pd.read_parquet(ROOT / "data" / f"pixels_{y}.parquet") for y in range(2020, 2024)],
               ignore_index=True)
out = ["# UrbanMask observation base: descriptive analysis", "",
       "Generated by `scripts/analysis.py` from the files in `data/`.", ""]

# 1. size and prevalence by year
by_year = df.groupby("year").agg(pixels=("label_built", "size"), built=("label_built", "sum"),
                                 polygons=("polygon_id", "nunique"))
by_year["prevalence_%"] = (100 * by_year.built / by_year.pixels).round(2)
tot = pd.DataFrame({"pixels": [len(df)], "built": [int(df.label_built.sum())],
                    "polygons": [df.polygon_id.nunique()],
                    "prevalence_%": [round(100 * df.label_built.mean(), 2)]}, index=["all"])
tab1 = pd.concat([by_year, tot]); tab1[["pixels", "built", "polygons"]] = tab1[["pixels", "built", "polygons"]].astype(int)
tab1.to_csv(RES / "pixels_by_year.csv")
out += ["## 1. Pixels and label prevalence by year", "", md(tab1), ""]

# 2. label transitions for the same pixel across years
key = df["lon"].round(6).astype(str) + "_" + df["lat"].round(6).astype(str)
wide = df.assign(key=key).pivot_table(index="key", columns="year", values="label_built", aggfunc="max")
complete = wide.dropna()
trans = []
for a, b in [(2020, 2021), (2021, 2022), (2022, 2023)]:
    x, y = complete[a], complete[b]
    trans.append({"from": a, "to": b, "pixels": len(complete), "0→1 (new built)": int(((x == 0) & (y == 1)).sum()),
                  "1→0 (built→not)": int(((x == 1) & (y == 0)).sum()),
                  "stable built": int(((x == 1) & (y == 1)).sum())})
trans = pd.DataFrame(trans).astype({"pixels": int})
trans["0→1 % of unbuilt"] = (100 * trans["0→1 (new built)"] / (trans.pixels - complete[trans["from"]].sum().values)).round(2)
trans.to_csv(RES / "label_transitions.csv", index=False)
ever = int(((complete[2020] == 0) & (complete[2023] == 1)).sum())
flick = int(((complete[[2020, 2021, 2022, 2023]].diff(axis=1).abs().sum(axis=1)) >= 2).sum())
out += ["## 2. Label transitions of the same pixel (pixels observed in all four years)", "",
        md(trans, index=False), "",
        f"- Pixels observed in all four years: {len(complete):,}",
        f"- Unbuilt in 2020 and built in 2023: {ever:,} ({100 * ever / (complete[2020] == 0).sum():.2f}% of the 2020 unbuilt pixels)",
        f"- Pixels whose label changes two or more times (flicker): {flick:,} ({100 * flick / len(complete):.2f}%)", ""]

# 3. feature statistics by class and univariate separability
y = df.label_built.values
rows = []
for f in FEAT:
    v = df[f].values
    q0 = np.nanpercentile(v[y == 0], [25, 50, 75]); q1 = np.nanpercentile(v[y == 1], [25, 50, 75])
    auc = roc_auc_score(y, v)
    rows.append({"feature": f, "median_unbuilt": q0[1], "IQR_unbuilt": f"{q0[0]:.3f}–{q0[2]:.3f}",
                 "median_built": q1[1], "IQR_built": f"{q1[0]:.3f}–{q1[2]:.3f}",
                 "ROC-AUC": round(max(auc, 1 - auc), 3), "direction": "higher if built" if auc >= 0.5 else "lower if built"})
feat = pd.DataFrame(rows).sort_values("ROC-AUC", ascending=False)
feat.to_csv(RES / "feature_separability.csv", index=False)
out += ["## 3. Features by class and univariate separability (all years)", "",
        md(feat, index=False, nd=3), ""]

# 4. correlation
corr = df[FEAT].corr().round(2)
corr.to_csv(RES / "feature_correlation.csv")
pairs = corr.where(np.triu(np.ones(corr.shape, bool), 1)).stack().sort_values(key=abs, ascending=False)
out += ["## 4. Strongest feature correlations (Pearson)", "",
        "\n".join(f"- {a} × {b}: {r:+.2f}" for (a, b), r in pairs.head(8).items()), ""]

# 5. HEU rule against the label, by year
heu = ((df.nbi > 0.18) & (df.ui > 0.05) & (df.ndvi < 0.20) & (df.mndwi > -0.50)).astype(int)
hr = []
for yr, d in df.assign(heu=heu).groupby("year"):
    tp = int(((d.heu == 1) & (d.label_built == 1)).sum()); fp = int(((d.heu == 1) & (d.label_built == 0)).sum())
    fn = int(((d.heu == 0) & (d.label_built == 1)).sum())
    p = tp / (tp + fp) if tp + fp else np.nan; r = tp / (tp + fn)
    hr.append({"year": yr, "flagged": tp + fp, "precision": round(p, 4), "recall": round(r, 4), "F1": round(2 * p * r / (p + r), 4)})
hr = pd.DataFrame(hr)
hr.to_csv(RES / "heuristic_by_year.csv", index=False)
out += ["## 5. HEU rule (NBI > 0.18, UI > 0.05, NDVI < 0.20, MNDWI > −0.50) against the label", "",
        md(hr, index=False, nd=4), ""]

# 6. spatial blocks
blk = df.groupby("block_3km").label_built.agg(["size", "mean"])
out += ["## 6. Spatial blocks (~3 km)", "",
        f"- Blocks: {len(blk)}; pixels per block: median {int(blk['size'].median()):,} (min {int(blk['size'].min())}, max {int(blk['size'].max()):,})",
        f"- Built prevalence across blocks: median {100 * blk['mean'].median():.1f}% (IQR {100 * blk['mean'].quantile(.25):.1f}–{100 * blk['mean'].quantile(.75):.1f}%)", ""]

# 7. Open Buildings presence score
pres = df.ob_presence
out += ["## 7. Open Buildings 2.5D Temporal presence score (`ob_presence`)", "",
        f"- Median {pres.median():.3f}; share ≥ 0.56: {100 * (pres >= 0.56).mean():.1f}% (label also requires height ≥ 2 m)",
        f"- Pixels with presence ≥ 0.56 but labelled unbuilt (height < 2 m): {int(((pres >= 0.56) & (df.label_built == 0)).sum()):,}", ""]

(RES / "summary.md").write_text("\n".join(out) + "\n", encoding="utf-8")

# figures
fig, ax = plt.subplots(1, 2, figsize=(7.2, 2.4))
ax[0].bar(by_year.index.astype(str), by_year["prevalence_%"], color="#2a6fdb")
for i, v in enumerate(by_year["prevalence_%"]): ax[0].text(i, v + 0.1, f"{v:.1f}", ha="center")
ax[0].set_ylabel("Built pixels (%)"); ax[0].set_title("(a) Label prevalence by year", loc="left")
ax[0].set_ylim(0, 9)
ax[1].barh(feat.feature[::-1], feat["ROC-AUC"][::-1], color="#2a6fdb"); ax[1].set_xlim(0.5, 1)
ax[1].set_xlabel("Univariate ROC-AUC"); ax[1].set_title("(b) Feature separability", loc="left")
for s in ["top", "right"]:
    ax[0].spines[s].set_visible(False); ax[1].spines[s].set_visible(False)
fig.tight_layout(); fig.savefig(FIG / "prevalence_and_separability.png", dpi=250); plt.close(fig)

fig, ax = plt.subplots(figsize=(4.6, 4))
im = ax.imshow(corr.values, cmap="RdBu_r", vmin=-1, vmax=1)
ax.set_xticks(range(len(FEAT))); ax.set_xticklabels(FEAT, rotation=90); ax.set_yticks(range(len(FEAT))); ax.set_yticklabels(FEAT)
fig.colorbar(im, fraction=0.046); ax.set_title("Pearson correlation of the 14 features")
fig.tight_layout(); fig.savefig(FIG / "feature_correlation.png", dpi=250); plt.close(fig)

top = feat.feature.head(6).tolist()
fig, axs = plt.subplots(1, 6, figsize=(7.2, 2.2))
samp = df.sample(200000, random_state=42)
for a, f in zip(axs, top):
    a.boxplot([samp.loc[samp.label_built == 0, f], samp.loc[samp.label_built == 1, f]], showfliers=False, widths=0.6)
    a.set_xticks([1, 2]); a.set_xticklabels(["unbuilt", "built"]); a.set_title(f)
fig.tight_layout(); fig.savefig(FIG / "top_features_by_class.png", dpi=250); plt.close(fig)
print("\n".join(out))
