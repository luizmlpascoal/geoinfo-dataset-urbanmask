"""Describe the monitored municipal public areas (APMs) and rebuild the UrbanMask pixel grid.

Usage: python scripts/apm_analysis.py
Writes results/apm_summary.md, results/apm_use_groups.csv and results/figures/apm_map.png.

The grid reproduces urbanMask.generate_pixel_grid_from_polygons
(https://github.com/ThiagoHF31/urbanMask): points every 0.00009° inside each
polygon (EPSG:4326), with one representative point for polygons that hold none.
"""
from pathlib import Path

import geopandas as gpd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from shapely import contains_xy

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
(RES / "figures").mkdir(parents=True, exist_ok=True)

apm = gpd.read_file(ROOT / "apms" / "apms_goiania.gpkg")
g = apm.to_crs(4326)
STEP = 0.00009


def n_pixels(geom):
    minx, miny, maxx, maxy = geom.bounds
    xs, ys = np.arange(minx, maxx, STEP), np.arange(miny, maxy, STEP)
    if len(xs) == 0 or len(ys) == 0:
        return 1
    X, Y = np.meshgrid(xs, ys)
    return max(int(contains_xy(geom, X.ravel(), Y.ravel()).sum()), 1)


apm["pixels"] = [n_pixels(geom) for geom in g.geometry]
apm["area_ha"] = apm.to_crs(31982).area / 1e4
GROUP_EN = {"AREAS VERDES-ZPA IV": "Green areas and protection zone IV", "INSTITUCIONAL": "Institutional",
            "DIVERSOS": "Miscellaneous", "SEM DESTINACAO": "No designated use", "PARQUES MUNICIPAIS": "Municipal parks",
            "RESERVAS ECOLOGICAS": "Ecological reserves", "OCUPANTES": "Occupants"}
apm["use_group"] = apm["nm_grupo_u"].map(GROUP_EN).fillna("Use group not informed")

tab = apm.groupby("use_group").agg(apms=("pixels", "size"), pixels=("pixels", "sum"), area_ha=("area_ha", "sum"),
                                   median_area_m2=("area_ha", lambda a: 1e4 * a.median())).sort_values("pixels", ascending=False)
tab.loc["Total"] = [len(apm), apm.pixels.sum(), apm.area_ha.sum(), 1e4 * apm.area_ha.median()]
tab = tab.round({"area_ha": 1, "median_area_m2": 0})
tab.to_csv(RES / "apm_use_groups.csv")

small = int((apm.pixels == 1).sum())
use = apm["nm_uso"].fillna("NAO INFORMADO").value_counts()
out = ["# Monitored municipal public areas (APMs)", "",
       "Generated by `scripts/apm_analysis.py` from `apms/apms_goiania.gpkg`.", "",
       f"- APMs: {len(apm):,}; total area {apm.area_ha.sum():,.1f} ha; median area {1e4 * apm.area_ha.median():,.0f} m²",
       f"- 10 m pixels in the UrbanMask grid: {int(apm.pixels.sum()):,} (reproduces the operational grid)",
       f"- APMs smaller than one pixel (one representative point): {small:,} ({100 * small / len(apm):.1f}%)",
       f"- Registered use 'INVASAO' (invasion): {int(use.get('INVASAO', 0))}; 'COMPROMETIDA' (compromised): {int(use.get('COMPROMETIDA', 0))}; "
       f"'LOTE' (plot): {int(use.get('LOTE', 0))}", "",
       "## By use group", "", tab.assign(apms=tab.apms.astype(int).map("{:,}".format), pixels=tab.pixels.astype(int).map("{:,}".format), area_ha=tab.area_ha.map("{:,.1f}".format), median_area_m2=tab.median_area_m2.astype(int).map("{:,}".format)).to_markdown(), "",
       "## Registered use (top 12)", "", use.head(12).to_frame("APMs").to_markdown(), ""]
(RES / "apm_summary.md").write_text("\n".join(out) + "\n", encoding="utf-8")

fig, ax = plt.subplots(figsize=(7, 4.6))
apm.to_crs(31982).plot(ax=ax, column="use_group", categorical=True, legend=True, linewidth=0, markersize=2,
                       legend_kwds={"fontsize": 6, "loc": "center left", "bbox_to_anchor": (1.0, 0.5), "frameon": False})
ax.set_axis_off(); ax.set_title("APMs monitored by UrbanMask, by use group (SIRGAS 2000 / UTM 22S)", fontsize=8)
fig.tight_layout(); fig.savefig(RES / "figures" / "apm_map.png", dpi=250); plt.close(fig)
print("\n".join(out))
